// Equivalenze tipografiche (es. apostrofo curvo -> dritto), applicate prima della ricerca.
inline constexpr char32_t FONT_EQUIVALENZE[4][2] = {
    { U'\U00002018', U'\U00000027' },
    { U'\U00002019', U'\U00000027' },
    { U'\U0000201C', U'\U00000022' },
    { U'\U0000201D', U'\U00000022' },
};

// Ricerca binaria; nullptr se il carattere non ha glifo (il test sui testi lo impedisce).
constexpr const Glifo* trova_glifo(char32_t c)
{
    for(const auto& e : FONT_EQUIVALENZE)
    {
        if(e[0] == c)
        {
            c = e[1];
        }
    }

    int basso = 0;
    int alto = GLIFI_FONT - 1;

    while(basso <= alto)
    {
        int medio = (basso + alto) / 2;

        if(FONT[medio].codice == c)
        {
            return &FONT[medio];
        }

        if(FONT[medio].codice < c)
        {
            basso = medio + 1;
        }
        else
        {
            alto = medio - 1;
        }
    }

    return nullptr;
}

